package com.v2ray.ang.dto

/**
 * Итог импорта: сколько добавлено ключей, сколько подписок - и сколько из этих
 * подписок так и не удалось скачать.
 *
 * Третьего числа раньше не было, и в этом была вся беда. Подписка по ссылке
 * заводится мгновенно, а содержимое её приходит отдельным запросом по сети. Импорт
 * отчитывался о первом и молчал о втором: человек видел «подписка добавлена», а
 * открывал пустую карточку, потому что сервер не ответил. Выглядело это как
 * «обновляется не с первого раза».
 *
 * Первые два поля стоят на своих местах нарочно: разбор вида
 * `val (count, countSub) = ...` работал с парой и продолжает работать с этим классом.
 *
 * @param count Добавлено отдельных ключей и конфигов.
 * @param countSub Заведено новых подписок.
 * @param subFailures Сколько из новых подписок не скачалось.
 */
data class BatchImportResult(
    val count: Int,
    val countSub: Int,
    val subFailures: Int = 0
) {
    /** Что-то добавилось, но часть подписок пришла пустой. */
    val hasSubFailures: Boolean get() = subFailures > 0
}
