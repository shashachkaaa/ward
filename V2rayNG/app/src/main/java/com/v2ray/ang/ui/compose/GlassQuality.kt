package com.v2ray.ang.ui.compose

import androidx.compose.runtime.compositionLocalOf

/**
 * Насколько тяжёлым делать стекло.
 *
 * Размытие и преломление считает видеоядро, и стоят они не поровну. Размытие -
 * штатная возможность системы, она хорошо оптимизирована. Преломление у края -
 * отдельная программа для видеоядра, и она заметно дороже; на экране таких
 * поверхностей десяток, и каждая считается заново каждый кадр.
 *
 * На быстрых устройствах это незаметно, на слабых видеоядрах - вроде Mali в младших
 * MediaTek - прокрутка начинает спотыкаться. Поэтому уровень выбирается, а не
 * навязывается: приложение не вправе решать за пользователя, что ему важнее -
 * внешний вид или плавность.
 */
enum class GlassQuality(val id: String) {

    /** Всё как задумано: размытие, преломление, блики. */
    FULL("full"),

    /** Без преломления: остаются размытие, тонировка и блик. Вдвое дешевле. */
    LITE("lite"),

    /** Без стекла вовсе: сплошные полупрозрачные поверхности. Дешевле некуда. */
    OFF("off");

    /** Размывать ли фон под поверхностью. */
    val blurs: Boolean get() = this != OFF

    /** Считать ли преломление у края. */
    val refracts: Boolean get() = this == FULL

    companion object {
        val Default: GlassQuality = FULL

        fun of(id: String?): GlassQuality =
            entries.firstOrNull { it.id == id } ?: Default
    }
}

/** Выбранный уровень. Тема кладёт его сюда, стекло читает. */
val LocalGlassQuality = compositionLocalOf { GlassQuality.Default }
