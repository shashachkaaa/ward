package com.v2ray.ang.ui.logcat

/**
 * Строка журнала вместе со своим неизменным номером.
 *
 * Номер не показывается и не значит ничего, кроме одного: это та же самая строка,
 * что и была. Список журнала держит последние несколько тысяч строк и старые
 * выбрасывает с начала, отчего у всех оставшихся сдвигаются порядковые номера. Если
 * опознавать строки по порядковому номеру, для списка это выглядит так, будто
 * содержимое разом поменялось у всех: человек стоит на своём месте, а текст под ним
 * уезжает вверх. Со сквозным номером список знает, что строка та же, и оставляет
 * человека там, где он был.
 *
 * @param id Сквозной номер с начала потока.
 * @param text Сама строка, как её отдал журнал.
 */
data class LogLine(val id: Long, val text: String)
