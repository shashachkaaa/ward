package com.v2ray.ang.ui.compose

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Разбор заметок к релизу.
 *
 * Проверяется не красота, а то, что до человека не доедет разметка вместо текста.
 * Заметки пишем мы, но читает их окно обновления - и всё, чего разбор не знает,
 * показывается решётками и звёздочками прямо в лицо. Так «### Безопасность» и
 * приехало в диалог: заголовков разбор не знал.
 */
class ReleaseNotesTest {

    private fun plain(markdown: String): String = parseSimpleMarkdown(markdown).text

    @Test
    fun `заголовок теряет решётки`() {
        assertEquals("Безопасность", plain("### Безопасность"))
    }

    @Test
    fun `заголовок любого уровня разбирается`() {
        assertEquals("Раз\nДва", plain("# Раз\n###### Два"))
    }

    @Test
    fun `заголовок распознаётся только с начала строки`() {
        assertEquals("шифр #12 готов", plain("шифр #12 готов"))
    }

    @Test
    fun `решётка без пробела заголовком не считается`() {
        assertEquals("#хештег", plain("#хештег"))
    }

    @Test
    fun `больше шести решёток - уже не заголовок`() {
        assertEquals("####### много", plain("####### много"))
    }

    @Test
    fun `жирный и курсив теряют звёздочки`() {
        assertEquals("жирный и курсив", plain("**жирный** и *курсив*"))
    }

    @Test
    fun `звёздочка списка не считается курсивом`() {
        assertEquals("* пункт с жирным", plain("* пункт с **жирным**"))
    }

    @Test
    fun `незакрытая разметка остаётся текстом`() {
        assertEquals("**незакрытый", plain("**незакрытый"))
    }

    @Test
    fun `моноширинный теряет обратные кавычки`() {
        assertEquals("profile-color", plain("`profile-color`"))
    }

    @Test
    fun `заголовок вперемешку с текстом и списком`() {
        val notes = "### Что починили\n\n- **Журнал** больше не уезжает\n- Кнопка `Продлить`"
        assertEquals("Что починили\n\n- Журнал больше не уезжает\n- Кнопка Продлить", plain(notes))
    }
}
